"""Regenerates apps/web/src/lib/revisions.ts, the list on the Revisions page, from git history.

One revision per week that had commits, numbered 1.0, 1.1, 1.2 ... in order. The newest is the version shown at the foot of the sidebar.
Run from the repo root:  python scripts/gen_revisions.py
Each entry lists up to 14 of that week's changes (fixes and test-only commits are counted, not listed) and how many commits the week held.
"""
import json
import re
import subprocess
from collections import OrderedDict
from datetime import datetime, timedelta

OUT = "apps/web/src/lib/revisions.ts"
NOISE = re.compile(r"^(fix|tests?|ci|chore|merge|revert|bump|wip|docs?: fix|lint|typo)\b", re.I)
MAX_LISTED = 14

raw = subprocess.run(
    ["git", "log", "--reverse", "--format=%ad|%s", "--date=format:%Y-%m-%d"],
    capture_output=True, text=True, encoding="utf-8", check=True,
).stdout.splitlines()

weeks: "OrderedDict[str, list]" = OrderedDict()
for line in raw:
    day, _, subject = line.partition("|")
    d = datetime.strptime(day, "%Y-%m-%d")
    monday = (d - timedelta(days=d.weekday())).strftime("%Y-%m-%d")
    weeks.setdefault(monday, []).append((day, subject.strip()))

entries = []
for i, (monday, commits) in enumerate(weeks.items()):
    clean = lambda s: re.sub(r"^(feat|docs|chore|perf|refactor|release)(\([^)]*\))?:\s*", "", re.sub(r"\s*\(#\d+\)$", "", s)).strip()
    features = [clean(s) for _, s in commits if s and not NOISE.match(s)]
    if not features:  # a week of only fixes: list some of them rather than nothing
        features = [clean(s) for _, s in commits if s][:8]
    # keep the order, but if there are many, sample evenly so the whole week is represented
    if len(features) > MAX_LISTED:
        step = len(features) / MAX_LISTED
        features = [features[int(k * step)] for k in range(MAX_LISTED)]
    features = [f[:220][:1].upper() + f[:220][1:] for f in features if f]
    entries.append({
        "version": f"1.{i}",
        "weekOf": monday,
        "lastChange": commits[-1][0],
        "commits": len(commits),
        "changes": features,
        "fixes": sum(1 for _, s in commits if NOISE.match(s)),
    })

entries.reverse()  # newest first
body = json.dumps(entries, indent=2, ensure_ascii=False)
ts = (
    "// Generated by scripts/gen_revisions.py from the git history. Do not edit by hand: run the script again.\n"
    "export interface Revision {\n  version: string;\n  weekOf: string;\n  lastChange: string;\n  commits: number;\n  changes: string[];\n  fixes: number;\n}\n\n"
    f"export const REVISIONS: Revision[] = {body};\n\n"
    "/** The current version: the newest revision. Shown at the foot of the sidebar. */\n"
    "export const APP_VERSION: string = REVISIONS[0].version;\n"
)
with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write(ts)
print(len(entries), "revisions; newest", entries[0]["version"])
